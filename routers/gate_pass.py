"""
Gate Pass — security-gate view of sold devices ready to exit the premises.

The guard (or any role granted the gate_pass module in the Permission Matrix)
sees every sold tag number with its Delivery Challan, and can confirm the
physical exit. The DC itself is the existing /invoices/waybill/{sale_id}
document — generated by the system at the time of sale.

The tag-number table is server-side DataTables (see /gate-pass/data) rather
than a single query capped at 500 rows rendered into the page — the old cap
meant any sale beyond the most recent 500 was simply invisible here, same
class of problem fixed on the Sales list page.
"""
